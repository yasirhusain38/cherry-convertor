function t(
  slug: string,
  name: string,
  kicker: string,
  h1: string,
  lede: string,
  metaTitle: string,
  keywords: string[],
  faqs: FaqItem[],
  related: string[],
  extra?: Partial<ToolDef>,
): ToolDef {
  return {
    slug,
    name,
    category: "pdf",
    mode: extra?.mode ?? "pdf-studio",
    kicker,
    h1,
    lede,
    metaTitle,
    metaDescription: `${lede} No upload. No account.`,
    keywords,
    faqs: [...faqs, local],
    related,
    ...extra,
  };
}

