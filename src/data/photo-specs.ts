export function getPhotoSpec(id: string): PhotoSpec {
  return PHOTO_SPECS.find((item) => item.id === id) ?? PHOTO_SPECS[0];
}

export function photoPixels(spec: PhotoSpec) {
  return {
    width: spec.widthPx ?? Math.round((spec.widthMm / 25.4) * spec.dpi),
    height: spec.heightPx ?? Math.round((spec.heightMm / 25.4) * spec.dpi),
  };
}

export function specsForCountry(countrySlug: string): PhotoSpec[] {
  return PHOTO_SPECS.filter((item) => item.countrySlug === countrySlug);
}
